<?php
/**
 * includes/provisioning.php — pure helpers for bin/provision_tenant.php and
 * bin/migrate_all.php: names, validation, the secrets file and argument parsing.
 *
 * Nothing here touches a database or the disk, so every rule is unit-tested
 * (tests/Unit/ProvisioningTest.php). The scripts do the side effects.
 */

require_once __DIR__ . '/tenant.php';

if (!function_exists('vk_prov_db_name')) {
    /**
     * A group's database AND MySQL user name: 'vk_' + the subdomain, hyphens as
     * underscores. MySQL user names stop at 32 characters, so a subdomain longer
     * than 29 cannot be provisioned (the shorter rule is enforced at creation).
     */
    function vk_prov_db_name(string $sub): string
    {
        return 'vk_' . str_replace('-', '_', $sub);
    }
}

if (!function_exists('vk_prov_validate_new')) {
    /**
     * Why a subdomain cannot be used for a new group, or null when it can.
     * $taken = subdomains already in the registry; $hosts = hosts already mapped.
     */
    function vk_prov_validate_new(string $sub, array $taken, array $hosts, string $baseDomain): ?string
    {
        if (!vk_tenant_valid_subdomain($sub)) {
            return "'$sub' is not a valid subdomain: 3 to 30 lowercase letters, digits or single hyphens, not starting or ending with a hyphen.";
        }
        if (strlen(vk_prov_db_name($sub)) > 32) {
            return "'$sub' is too long: its MySQL user name would pass 32 characters. Use 29 characters or fewer.";
        }
        if (in_array($sub, vk_tenant_reserved_subdomains(), true)) {
            return "'$sub' is reserved.";
        }
        if (in_array($sub, $taken, true)) {
            return "A group with the subdomain '$sub' already exists.";
        }
        if (in_array($sub . '.' . $baseDomain, $hosts, true)) {
            return "The host $sub.$baseDomain is already mapped to a group.";
        }
        return null;
    }
}

if (!function_exists('vk_prov_valid_db_identifier')) {
    /** A database or user name we are willing to put inside backticks or quotes. */
    function vk_prov_valid_db_identifier(string $name): bool
    {
        return (bool) preg_match('/^[A-Za-z0-9_]{1,64}$/', $name);
    }
}

if (!function_exists('vk_prov_secret')) {
    /** A random secret: URL-safe, no quotes or backslashes, so it is safe in SQL and PHP strings. */
    function vk_prov_secret(int $bytes = 24): string
    {
        return rtrim(strtr(base64_encode(random_bytes($bytes)), '+/', '-_'), '=');
    }
}

if (!function_exists('vk_prov_secrets_file')) {
    /** The contents of /etc/vikundi/tenants/<subdomain>.php. */
    function vk_prov_secrets_file(string $dbPassword, string $jwtSecret): string
    {
        return "<?php\n// Vikundi group secrets. Generated by bin/provision_tenant.php; do not commit.\n"
            . 'return ' . var_export(['db_password' => $dbPassword, 'jwt_secret' => $jwtSecret], true) . ";\n";
    }
}

if (!function_exists('vk_prov_data_dirs')) {
    /** The folders every group has under the data root. */
    function vk_prov_data_dirs(): array
    {
        return ['uploads', 'assets/images', 'downloads', 'backups', 'sessions', 'private'];
    }
}

if (!function_exists('vk_prov_username')) {
    /** The app's username convention: first initial + last name, lowercase letters only. */
    function vk_prov_username(string $first, string $last): string
    {
        $u = strtolower(substr(trim($first), 0, 1) . trim($last));
        return preg_replace('/[^a-z]/', '', $u) ?? '';
    }
}

if (!function_exists('vk_prov_parse_args')) {
    /**
     * --key=value and bare --flag arguments → ['key' => 'value', 'flag' => true].
     * A value may also follow as the next argument (--name "Wise Wallet").
     */
    function vk_prov_parse_args(array $argv): array
    {
        $out = [];
        $args = array_values(array_slice($argv, 1));
        for ($i = 0; $i < count($args); $i++) {
            $a = (string) $args[$i];
            if (!str_starts_with($a, '--')) {
                continue;
            }
            $a = substr($a, 2);
            if (str_contains($a, '=')) {
                [$k, $v] = explode('=', $a, 2);
                $out[$k] = $v;
            } elseif (isset($args[$i + 1]) && !str_starts_with((string) $args[$i + 1], '--')) {
                $out[$a] = (string) $args[++$i];
            } else {
                $out[$a] = true;
            }
        }
        return $out;
    }
}

if (!function_exists('vk_prov_status_change')) {
    /**
     * The registry update for --suspend / --resume / --archive, or an error.
     * Returns [newStatus, timestampColumn|null] or a string explaining the refusal.
     */
    function vk_prov_status_change(string $action, string $current): array|string
    {
        return match (true) {
            $action === 'suspend' && $current === 'active'    => ['suspended', 'suspended_at'],
            $action === 'resume'  && $current === 'suspended' => ['active', null],
            $action === 'archive' && in_array($current, ['active', 'suspended'], true) => ['archived', 'archived_at'],
            default => "Cannot $action a group that is $current.",
        };
    }
}
